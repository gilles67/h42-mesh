from typing import TYPE_CHECKING, Any
from uuid import UUID

from tortoise import fields
from tortoise.backends.base.client import BaseDBAsyncClient
from tortoise.exceptions import IntegrityError, ValidationError

from h42mesh.controller.models.base import BaseModel
from h42mesh.controller.models.connection import Connection
from h42mesh.controller.models.enums import AddressFamily
from h42mesh.controller.models.validators import (
    PublicKeyValidator,
    TunnelIPv4NetworkValidator,
    TunnelIPv6NetworkValidator,
    ipv6_network_for,
    range_validators,
)

if TYPE_CHECKING:
    from collections.abc import Iterable

    from h42mesh.controller.models.mesh import Mesh
    from h42mesh.controller.models.router import Router


class Tunnel(BaseModel):
    """A tunnel between two connections of routers of different sites, in one mesh.

    ``a`` listens and takes the first address of each pair, ``b`` initiates
    and takes the second. Consistency with the stored data is checked on save
    (not for bulk queryset operations); tunnel selection rules (backup/backup,
    ``direct``) belong to the tunnel computation, not to the model.
    """

    # Direct reference so the database enforces uniqueness within the mesh.
    mesh: fields.ForeignKeyRelation["Mesh"] = fields.ForeignKeyField(
        "models.Mesh", related_name="tunnels", on_delete=fields.RESTRICT
    )
    connection_a: fields.ForeignKeyRelation["Connection"] = fields.ForeignKeyField(
        "models.Connection", related_name="tunnels_as_a", on_delete=fields.CASCADE
    )
    connection_b: fields.ForeignKeyRelation["Connection"] = fields.ForeignKeyField(
        "models.Connection", related_name="tunnels_as_b", on_delete=fields.CASCADE
    )
    ipv4_network = fields.CharField(max_length=18, validators=[TunnelIPv4NetworkValidator()])
    ipv6_network = fields.CharField(max_length=43, validators=[TunnelIPv6NetworkValidator()])
    public_key_a = fields.CharField(max_length=44, null=True, validators=[PublicKeyValidator()])
    public_key_b = fields.CharField(max_length=44, null=True, validators=[PublicKeyValidator()])
    # Encrypted WireGuard PSK (JSON object: v, kdf, salt, nonce, ciphertext).
    preshared_key: dict[str, Any] = fields.JSONField()
    port_a = fields.IntField(null=True, validators=range_validators(1, 65535))
    port_b = fields.IntField(null=True, validators=range_validators(1, 65535))

    # Foreign key columns, generated by Tortoise (declared for type checking).
    mesh_id: UUID
    connection_a_id: UUID
    connection_b_id: UUID

    statuses: fields.ReverseRelation["TunnelStatus"]

    class Meta:
        table = "tunnel"
        unique_together = (
            ("connection_a", "connection_b"),
            ("mesh", "ipv4_network"),
            ("mesh", "ipv6_network"),
        )

    async def save(
        self,
        using_db: BaseDBAsyncClient | None = None,
        update_fields: "Iterable[str] | None" = None,
        force_create: bool = False,
        force_update: bool = False,
    ) -> None:
        await self._check_consistency(using_db)
        await super().save(using_db, update_fields, force_create, force_update)

    async def _check_consistency(self, using_db: BaseDBAsyncClient | None) -> None:
        if self.ipv6_network != ipv6_network_for(self.ipv4_network):
            raise ValidationError(
                f"ipv6_network {self.ipv6_network!r} is not derived from {self.ipv4_network!r}"
            )
        if self.connection_a_id == self.connection_b_id:
            raise ValidationError("a tunnel cannot link a connection to itself")

        connections = {
            c.id: c
            for c in await Connection.filter(id__in=[self.connection_a_id, self.connection_b_id])
            .using_db(using_db)
            .select_related("router__site")
        }
        end_a = connections.get(self.connection_a_id)
        end_b = connections.get(self.connection_b_id)
        if end_a is None or end_b is None:
            raise ValidationError("both tunnel connections must exist")
        site_a = end_a.router.site
        site_b = end_b.router.site
        if site_a.id == site_b.id:
            raise ValidationError("a tunnel must link routers of different sites")
        if not site_a.mesh_id == site_b.mesh_id == self.mesh_id:
            raise ValidationError("both connections must belong to the tunnel's mesh")

        reverse = Tunnel.filter(
            connection_a_id=self.connection_b_id, connection_b_id=self.connection_a_id
        )
        if self._saved_in_db:
            reverse = reverse.exclude(id=self.id)
        if await reverse.using_db(using_db).exists():
            raise IntegrityError("the same tunnel already exists in the other direction")


class TunnelStatus(BaseModel):
    """State of a tunnel as reported by one end's agent (one row per tunnel and end)."""

    tunnel: fields.ForeignKeyRelation[Tunnel] = fields.ForeignKeyField(
        "models.Tunnel", related_name="statuses", on_delete=fields.CASCADE
    )
    router: fields.ForeignKeyRelation["Router"] = fields.ForeignKeyField(
        "models.Router", related_name="tunnel_statuses", on_delete=fields.CASCADE
    )
    family_in_use = fields.CharEnumField(AddressFamily, max_length=8, null=True)
    last_handshake_at = fields.DatetimeField(null=True)
    bgp_established = fields.BooleanField(default=False)
    reported_at = fields.DatetimeField()

    tunnel_id: UUID
    router_id: UUID

    class Meta:
        table = "tunnel_status"
        unique_together = (("tunnel", "router"),)

    async def save(
        self,
        using_db: BaseDBAsyncClient | None = None,
        update_fields: "Iterable[str] | None" = None,
        force_create: bool = False,
        force_update: bool = False,
    ) -> None:
        ends = (
            await Tunnel.filter(id=self.tunnel_id)
            .using_db(using_db)
            .values_list("connection_a__router_id", "connection_b__router_id")
        )
        if not ends or self.router_id not in ends[0]:
            raise ValidationError("the reporting router is not an end of the tunnel")
        await super().save(using_db, update_fields, force_create, force_update)
