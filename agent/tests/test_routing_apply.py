"""System settings and FRR reload, with a fake system."""

from pathlib import Path

import pytest

from frr_cases import LINKS, backup_tunnel
from h42mesh.agent.routing import sysctl
from h42mesh.agent.routing.apply import FRR_CONF, RoutingApplier, RoutingError, SystemAccess


class FakeSystem:
    def __init__(self, links: list[str] | None = None) -> None:
        self.files: dict[Path, str] = {}
        self.reloads = 0
        self.reload_fails = False
        self.link_names = links if links is not None else [*LINKS, "wd0c0rootr0c0"]

    def read(self, path: Path) -> str | None:
        return self.files.get(path)

    def write(self, path: Path, text: str) -> None:
        self.files[path] = text

    def write_frr_config(self, path: Path, text: str) -> None:
        self.files[path] = text

    def reload_frr(self, path: Path) -> None:
        if self.reload_fails:
            raise RoutingError("frr-reload failed: syntax")
        self.reloads += 1

    def links(self) -> list[str]:
        return self.link_names


@pytest.fixture
def system() -> FakeSystem:
    return FakeSystem()


def apply(system: FakeSystem) -> RoutingApplier:
    checked: SystemAccess = system
    applier = RoutingApplier(checked)
    applier.apply_now(*backup_tunnel())
    return applier


# --- FRR ---------------------------------------------------------------------


def test_frr_written_and_reloaded(system: FakeSystem) -> None:
    apply(system)
    assert system.reloads == 1
    assert system.files[FRR_CONF].startswith("! Generated by h42-mesh-agent")


def test_no_reload_without_change(system: FakeSystem) -> None:
    applier = apply(system)
    applier.apply_now(*backup_tunnel())
    assert system.reloads == 1


def test_no_reload_after_a_restart_of_the_agent(system: FakeSystem) -> None:
    apply(system)
    apply(system)  # new applier, same file: FRR already loaded it
    assert system.reloads == 1


def test_reload_when_the_file_was_changed(system: FakeSystem) -> None:
    applier = apply(system)
    system.files[FRR_CONF] += "! edited by hand\n"
    applier.apply_now(*backup_tunnel())
    assert system.reloads == 2


def test_failed_reload_is_tried_again(system: FakeSystem) -> None:
    system.reload_fails = True
    applier = apply(system)
    assert applier.reload_failed and system.reloads == 0
    system.reload_fails = False
    applier.apply_now(*backup_tunnel())
    assert system.reloads == 1 and not applier.reload_failed


# --- sysctls -----------------------------------------------------------------


def test_reserved_ports_of_the_router(system: FakeSystem) -> None:
    system.files[sysctl.RESERVED_PORTS] = "8080,9000-9010\n"
    apply(system)
    assert system.files[sysctl.RESERVED_PORTS] == "8080,9000-9010,42000-42999"


def test_reserved_ports_written_only_if_different(system: FakeSystem) -> None:
    system.files[sysctl.RESERVED_PORTS] = "42000-42999\n"
    apply(system)
    assert system.files[sysctl.RESERVED_PORTS] == "42000-42999\n"  # untouched


def test_rp_filter_of_the_tunnels(system: FakeSystem) -> None:
    path = sysctl.rp_filter_path("wd0c0rootr0c0")
    system.files[path] = "1\n"
    system.files[sysctl.rp_filter_path("eth0")] = "1\n"
    apply(system)
    assert system.files[path] == "2"
    assert system.files[sysctl.rp_filter_path("eth0")] == "1\n"  # not a tunnel


@pytest.mark.parametrize(
    ("current", "router", "expected"),
    [
        ("", range(42000, 43000), "42000-42999"),
        ("43000-43999", range(42000, 43000), "42000-42999"),  # previous router number
        ("44000-44999", range(42000, 43000), "42000-42999,44000-44999"),  # another mesh
        ("22,8000-8100", range(43000, 44000), "22,8000-8100,43000-43999"),
        ("42000-42999", range(42000, 43000), "42000-42999"),
    ],
)
def test_reserved_ports_value(current: str, router: range, expected: str) -> None:
    assert sysctl.reserved_ports(current, 0, router) == expected


def test_same_ports() -> None:
    assert sysctl.same_ports("42000-42499,42500-42999", "42000-42999\n")
    assert not sysctl.same_ports("42000-42998", "42000-42999")


def test_invalid_ports() -> None:
    with pytest.raises(ValueError):
        sysctl.parse_ports("9-8")
