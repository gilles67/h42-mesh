"""Tunnel interfaces seen from the system (Linux): links, addresses, sysctls.

pyroute2 is imported when used: it does not load on other systems, where the
pure functions of this module are still tested. The rest is covered by the
integration tests (Linux, root).
"""

import ipaddress
from collections.abc import Iterable
from pathlib import Path
from typing import Any

Address = ipaddress.IPv4Interface | ipaddress.IPv6Interface

PROC_SYS = Path("/proc/sys/net")
_IPRoute = Any  # pyroute2.IPRoute, without type annotations


def address_changes(
    current: Iterable[Address], wanted: Iterable[Address]
) -> tuple[list[Address], list[Address]]:
    """(to add, to remove): the interface ends with exactly the wanted addresses
    (an fe80:: address generated by the kernel is removed, for instance)."""
    have, want = set(current), set(wanted)
    order = lambda a: (a.version, int(a.ip))  # noqa: E731
    return sorted(want - have, key=order), sorted(have - want, key=order)


def interface_sysctls(name: str) -> dict[Path, str]:
    """Before the interface is up: no address generated by the kernel, loose rp_filter."""
    return {
        PROC_SYS / "ipv6" / "conf" / name / "addr_gen_mode": "1",
        PROC_SYS / "ipv4" / "conf" / name / "rp_filter": "2",
    }


def _iproute() -> _IPRoute:
    from pyroute2 import IPRoute  # Linux only

    return IPRoute()


def _index(ipr: _IPRoute, name: str) -> int | None:
    found = ipr.link_lookup(ifname=name)
    return int(found[0]) if found else None


def link_names() -> list[str]:
    with _iproute() as ipr:
        return sorted(str(link.get_attr("IFLA_IFNAME")) for link in ipr.get_links())


def link_exists(name: str) -> bool:
    with _iproute() as ipr:
        return _index(ipr, name) is not None


def _addresses(ipr: _IPRoute, index: int) -> list[Address]:
    found: list[Address] = []
    for message in ipr.get_addr(index=index):
        address = message.get_attr("IFA_LOCAL") or message.get_attr("IFA_ADDRESS")
        found.append(ipaddress.ip_interface(f"{address}/{message['prefixlen']}"))
    return found


def setup_interface(name: str, addresses: Iterable[Address]) -> None:
    """Sysctls, exactly ``addresses``, then up. Idempotent."""
    for path, value in interface_sysctls(name).items():
        if path.read_text().strip() != value:
            path.write_text(value)
    with _iproute() as ipr:
        index = _index(ipr, name)
        if index is None:
            raise LookupError(f"interface {name} does not exist")
        add, remove = address_changes(_addresses(ipr, index), addresses)
        for address in remove:
            ipr.addr(
                "del", index=index, address=str(address.ip), prefixlen=address.network.prefixlen
            )
        for address in add:
            ipr.addr(
                "add", index=index, address=str(address.ip), prefixlen=address.network.prefixlen
            )
        ipr.link("set", index=index, state="up")


def delete_link(name: str) -> None:
    with _iproute() as ipr:
        index = _index(ipr, name)
        if index is not None:
            ipr.link("del", index=index)
